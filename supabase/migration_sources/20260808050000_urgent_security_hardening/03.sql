create or replace function public.enforce_field_feed_insert_rate_limits()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  recent_count integer;
  daily_count integer;
  caller uuid := auth.uid();
begin
  if caller is null then
    raise exception 'Authentication required';
  end if;
  if not public.brinesearch_user_email_verified(caller) then
    raise exception 'Verify your email before posting';
  end if;
  if tg_table_name='field_posts' then
    select count(*) into recent_count from public.field_posts
      where author_id=caller and created_at>now()-interval '10 minutes';
    select count(*) into daily_count from public.field_posts
      where author_id=caller and created_at>now()-interval '24 hours';
    if recent_count>=3 or daily_count>=12 then
      raise exception 'Post limit reached. Try again later.';
    end if;
  elsif tg_table_name='field_comments' then
    select count(*) into recent_count from public.field_comments
      where author_id=caller and created_at>now()-interval '10 minutes';
    select count(*) into daily_count from public.field_comments
      where author_id=caller and created_at>now()-interval '24 hours';
    if recent_count>=12 or daily_count>=60 then
      raise exception 'Comment limit reached. Try again later.';
    end if;
  elsif tg_table_name='field_reports' then
    select count(*) into recent_count from public.field_reports
      where reporter_id=caller and created_at>now()-interval '1 hour';
    select count(*) into daily_count from public.field_reports
      where reporter_id=caller and created_at>now()-interval '24 hours';
    if recent_count>=3 or daily_count>=10 then
      raise exception 'Report limit reached. Try again later.';
    end if;
  elsif tg_table_name='field_post_votes' then
    select count(*) into recent_count from public.field_post_votes
      where user_id=caller and created_at>now()-interval '10 minutes';
    select count(*) into daily_count from public.field_post_votes
      where user_id=caller and created_at>now()-interval '24 hours';
    if recent_count>=30 or daily_count>=200 then
      raise exception 'Vote limit reached. Try again later.';
    end if;
  end if;
  return new;
end;
