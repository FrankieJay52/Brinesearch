       or new.created_at is distinct from old.created_at then
      raise exception 'Protected profile fields may only be changed by a moderator';
    end if;
    if new.status is distinct from old.status then
      if old.user_id is distinct from caller then
        raise exception 'Profile status change is not allowed';
      end if;
      if old.status='suspended' then
        raise exception 'A suspended profile may only be restored by a moderator';
      end if;
      if not (
        (old.status='active' and new.status='removed')
        or (old.status='removed' and new.status='active')
      ) then
        raise exception 'Profile status change is not allowed';
      end if;
    end if;
  end if;
  return new;
end;
